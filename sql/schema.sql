GO

/* ---------- Users (login / signup) ---------- */
IF OBJECT_ID(N'eSign.Users', N'U') IS NULL
CREATE TABLE eSign.Users (
  Id              NVARCHAR(32)  NOT NULL CONSTRAINT PK_Users PRIMARY KEY,
  OrganisationId  NVARCHAR(32)  NOT NULL CONSTRAINT FK_Users_Organisations REFERENCES eSign.Organisations (Id),
  Name            NVARCHAR(200) NOT NULL,
  Email           NVARCHAR(320) NOT NULL CONSTRAINT UQ_Users_Email UNIQUE,   -- stored lower-case
  PasswordHash    NVARCHAR(100) NOT NULL,                                     -- bcrypt hash, never the password
  Role            NVARCHAR(20)  NOT NULL CONSTRAINT DF_Users_Role DEFAULT N'admin'
                                CONSTRAINT CK_Users_Role CHECK (Role IN (N'admin', N'member')),
  IsActive        BIT           NOT NULL CONSTRAINT DF_Users_IsActive DEFAULT 1,
  CreatedAt       DATETIME2(0)  NOT NULL CONSTRAINT DF_Users_CreatedAt DEFAULT SYSUTCDATETIME(),
  LastLoginAt     DATETIME2(0)  NULL
);
GO

