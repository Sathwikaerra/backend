/*
  eSign Doc Builder - MS SQL Server schema
  -----------------------------------------
  All tables live in the eSign schema inside an EXISTING database.
  - SSMS / Azure Data Studio: select your database first, then run this script.
  - Or let the backend do it:  npm run db:init   (uses DB_NAME and DB_SCHEMA from backend/.env;
    a different DB_SCHEMA replaces "eSign" below automatically)
  Safe to re-run: every object is created only if it does not exist yet.

  Design notes
  - Every business table carries OrganisationId, and the API always filters by it,
    so each organisation only ever sees its own data.
  - Ids are 24-char hex strings generated by the API (same format the frontend shows).
  - Nested workflow settings that the UI edits as one unit (basic / advanced / eStamp
    settings, participants, signature box coordinates) are stored as JSON columns,
    guarded with ISJSON checks. Things you query or report on are real columns.
*/

/* CREATE SCHEMA has to run in its own batch, so it goes through EXEC */
IF SCHEMA_ID(N'eSign') IS NULL
  EXEC(N'CREATE SCHEMA eSign');
GO

/* ---------- Organisations ---------- */
IF OBJECT_ID(N'eSign.Organisations', N'U') IS NULL
CREATE TABLE eSign.Organisations (
  Id         NVARCHAR(32)  NOT NULL CONSTRAINT PK_Organisations PRIMARY KEY,
  Name       NVARCHAR(200) NOT NULL,
  CreatedAt  DATETIME2(0)  NOT NULL CONSTRAINT DF_Organisations_CreatedAt DEFAULT SYSUTCDATETIME()
);
GO

/* ---------- Users (login / signup) ---------- */
IF OBJECT_ID(N'eSign.Users', N'U') IS NULL
CREATE TABLE eSign.Users (
  Id              NVARCHAR(32)  NOT NULL CONSTRAINT PK_Users PRIMARY KEY,
  OrganisationId  NVARCHAR(32)  NOT NULL CONSTRAINT FK_Users_Organisations REFERENCES eSign.Organisations (Id),
  Name            NVARCHAR(200) NOT NULL,
  Email           NVARCHAR(320) NOT NULL CONSTRAINT UQ_Users_Email UNIQUE,   -- stored lower-case
  PasswordHash    NVARCHAR(100) NOT NULL,                                     -- bcrypt hash, never the password
  Role            NVARCHAR(20)  NOT NULL CONSTRAINT DF_Users_Role DEFAULT N'admin'
                                CONSTRAINT CK_Users_Role CHECK (Role IN (N'admin', N'member')),
  IsActive        BIT           NOT NULL CONSTRAINT DF_Users_IsActive DEFAULT 1,
  CreatedAt       DATETIME2(0)  NOT NULL CONSTRAINT DF_Users_CreatedAt DEFAULT SYSUTCDATETIME(),
  LastLoginAt     DATETIME2(0)  NULL
);
GO

/* ---------- Workflows ---------- */
IF OBJECT_ID(N'eSign.Workflows', N'U') IS NULL
CREATE TABLE eSign.Workflows (
  Id                 NVARCHAR(32)   NOT NULL CONSTRAINT PK_Workflows PRIMARY KEY,
  OrganisationId     NVARCHAR(32)   NOT NULL CONSTRAINT FK_Workflows_Organisations REFERENCES eSign.Organisations (Id),
  Name               NVARCHAR(200)  NOT NULL,
  Status             NVARCHAR(20)   NOT NULL CONSTRAINT CK_Workflows_Status CHECK (Status IN (N'active', N'inactive', N'draft')),
  Type               NVARCHAR(20)   NOT NULL CONSTRAINT DF_Workflows_Type DEFAULT N'Pdf',
  SigningMethod      NVARCHAR(20)   NOT NULL CONSTRAINT DF_Workflows_SigningMethod DEFAULT N'sequential',
  DocumentName       NVARCHAR(260)  NULL,
  BasicJson          NVARCHAR(MAX)  NOT NULL CONSTRAINT CK_Workflows_BasicJson CHECK (ISJSON(BasicJson) = 1),
  AdvancedJson       NVARCHAR(MAX)  NOT NULL CONSTRAINT CK_Workflows_AdvancedJson CHECK (ISJSON(AdvancedJson) = 1),
  EstampJson         NVARCHAR(MAX)  NOT NULL CONSTRAINT CK_Workflows_EstampJson CHECK (ISJSON(EstampJson) = 1),
  ParticipantsJson   NVARCHAR(MAX)  NOT NULL CONSTRAINT CK_Workflows_ParticipantsJson CHECK (ISJSON(ParticipantsJson) = 1),
  BoxesJson          NVARCHAR(MAX)  NOT NULL CONSTRAINT CK_Workflows_BoxesJson CHECK (ISJSON(BoxesJson) = 1),
  InitiationMessage  NVARCHAR(2000) NULL,
  CreatedBy          NVARCHAR(32)   NULL CONSTRAINT FK_Workflows_Users REFERENCES eSign.Users (Id),
  CreatedAt          DATETIME2(0)   NOT NULL CONSTRAINT DF_Workflows_CreatedAt DEFAULT SYSUTCDATETIME(),
  UpdatedAt          DATETIME2(0)   NOT NULL CONSTRAINT DF_Workflows_UpdatedAt DEFAULT SYSUTCDATETIME()
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_Workflows_Org_Status' AND object_id = OBJECT_ID(N'eSign.Workflows'))
  CREATE INDEX IX_Workflows_Org_Status ON eSign.Workflows (OrganisationId, Status, CreatedAt DESC);
GO

/* The uploaded / generated contract PDF, one per workflow */
IF OBJECT_ID(N'eSign.WorkflowFiles', N'U') IS NULL
CREATE TABLE eSign.WorkflowFiles (
  WorkflowId   NVARCHAR(32)   NOT NULL CONSTRAINT PK_WorkflowFiles PRIMARY KEY
                              CONSTRAINT FK_WorkflowFiles_Workflows REFERENCES eSign.Workflows (Id) ON DELETE CASCADE,
  FileName     NVARCHAR(260)  NOT NULL,
  ContentType  NVARCHAR(100)  NOT NULL CONSTRAINT DF_WorkflowFiles_ContentType DEFAULT N'application/pdf',
  SizeBytes    INT            NOT NULL,
  Data         VARBINARY(MAX) NOT NULL,
  UploadedAt   DATETIME2(0)   NOT NULL CONSTRAINT DF_WorkflowFiles_UploadedAt DEFAULT SYSUTCDATETIME()
);
GO

/* Every save of a workflow, for the "Show Version History" panel */
IF OBJECT_ID(N'eSign.WorkflowVersions', N'U') IS NULL
CREATE TABLE eSign.WorkflowVersions (
  Id            INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_WorkflowVersions PRIMARY KEY,
  WorkflowId    NVARCHAR(32)  NOT NULL CONSTRAINT FK_WorkflowVersions_Workflows REFERENCES eSign.Workflows (Id) ON DELETE CASCADE,
  Version       INT           NOT NULL,
  Status        NVARCHAR(20)  NOT NULL,
  SnapshotJson  NVARCHAR(MAX) NOT NULL CONSTRAINT CK_WorkflowVersions_Snapshot CHECK (ISJSON(SnapshotJson) = 1),
  SavedBy       NVARCHAR(32)  NULL,
  SavedAt       DATETIME2(0)  NOT NULL CONSTRAINT DF_WorkflowVersions_SavedAt DEFAULT SYSUTCDATETIME(),
  CONSTRAINT UQ_WorkflowVersions UNIQUE (WorkflowId, Version)
);
GO

/* ---------- Templates (Word-style document + signing setup) ---------- */
IF OBJECT_ID(N'eSign.Templates', N'U') IS NULL
CREATE TABLE eSign.Templates (
  Id                NVARCHAR(32)   NOT NULL CONSTRAINT PK_Templates PRIMARY KEY,
  OrganisationId    NVARCHAR(32)   NOT NULL CONSTRAINT FK_Templates_Organisations REFERENCES eSign.Organisations (Id),
  Name              NVARCHAR(200)  NOT NULL,
  Description       NVARCHAR(1000) NULL,
  SigningMethod     NVARCHAR(20)   NOT NULL CONSTRAINT DF_Templates_SigningMethod DEFAULT N'sequential',
  StampingMethod    NVARCHAR(40)   NULL,
  ExpiryValue       INT            NOT NULL CONSTRAINT DF_Templates_ExpiryValue DEFAULT 14,
  ExpiryUnit        NVARCHAR(10)   NOT NULL CONSTRAINT DF_Templates_ExpiryUnit DEFAULT N'days',
  ParticipantsJson  NVARCHAR(MAX)  NOT NULL CONSTRAINT CK_Templates_ParticipantsJson CHECK (ISJSON(ParticipantsJson) = 1),
  ContentHtml       NVARCHAR(MAX)  NOT NULL,
  PageSetupJson     NVARCHAR(400)  NOT NULL CONSTRAINT CK_Templates_PageSetupJson CHECK (ISJSON(PageSetupJson) = 1),
  CreatedBy         NVARCHAR(32)   NULL CONSTRAINT FK_Templates_Users REFERENCES eSign.Users (Id),
  CreatedAt         DATETIME2(0)   NOT NULL CONSTRAINT DF_Templates_CreatedAt DEFAULT SYSUTCDATETIME(),
  UpdatedAt         DATETIME2(0)   NOT NULL CONSTRAINT DF_Templates_UpdatedAt DEFAULT SYSUTCDATETIME()
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_Templates_Org' AND object_id = OBJECT_ID(N'eSign.Templates'))
  CREATE INDEX IX_Templates_Org ON eSign.Templates (OrganisationId, UpdatedAt DESC);
GO

/* ---------- Contracts (a workflow initiated for real signers) ---------- */
IF OBJECT_ID(N'eSign.Contracts', N'U') IS NULL
CREATE TABLE eSign.Contracts (
  Id              NVARCHAR(32)  NOT NULL CONSTRAINT PK_Contracts PRIMARY KEY,
  OrganisationId  NVARCHAR(32)  NOT NULL CONSTRAINT FK_Contracts_Organisations REFERENCES eSign.Organisations (Id),
  WorkflowId      NVARCHAR(32)  NULL CONSTRAINT FK_Contracts_Workflows REFERENCES eSign.Workflows (Id) ON DELETE SET NULL,
  Name            NVARCHAR(200) NOT NULL,
  WorkflowName    NVARCHAR(200) NOT NULL,
  Estamping       NVARCHAR(40)  NULL,
  Status          NVARCHAR(20)  NOT NULL CONSTRAINT DF_Contracts_Status DEFAULT N'incomplete'
                                CONSTRAINT CK_Contracts_Status CHECK (Status IN (N'incomplete', N'completed', N'cancelled')),
  CreatedBy       NVARCHAR(32)  NULL CONSTRAINT FK_Contracts_Users REFERENCES eSign.Users (Id),
  CreatedAt       DATETIME2(0)  NOT NULL CONSTRAINT DF_Contracts_CreatedAt DEFAULT SYSUTCDATETIME(),
  ExpiresAt       DATETIME2(0)  NOT NULL,
  CompletedAt     DATETIME2(0)  NULL
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_Contracts_Org_Created' AND object_id = OBJECT_ID(N'eSign.Contracts'))
  CREATE INDEX IX_Contracts_Org_Created ON eSign.Contracts (OrganisationId, CreatedAt DESC);
GO

IF OBJECT_ID(N'eSign.ContractSigners', N'U') IS NULL
CREATE TABLE eSign.ContractSigners (
  Id           INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_ContractSigners PRIMARY KEY,
  ContractId   NVARCHAR(32)  NOT NULL CONSTRAINT FK_ContractSigners_Contracts REFERENCES eSign.Contracts (Id) ON DELETE CASCADE,
  SignerOrder  INT           NOT NULL,
  Name         NVARCHAR(200) NOT NULL,
  Email        NVARCHAR(320) NOT NULL,
  Method       NVARCHAR(40)  NULL,
  Signed       BIT           NOT NULL CONSTRAINT DF_ContractSigners_Signed DEFAULT 0,
  SignedAt     DATETIME2(0)  NULL,
  CONSTRAINT UQ_ContractSigners_Order UNIQUE (ContractId, SignerOrder)
);
GO

/*
  "Expired" is not stored: an incomplete contract whose ExpiresAt has passed is
  reported as expired by the API, so the status is always current.
*/

/* ---------- Email OTPs for login / signup verification (also: migrations/001_email_otps.sql) ---------- */
IF OBJECT_ID(N'eSign.EmailOtps', N'U') IS NULL
CREATE TABLE eSign.EmailOtps (
  Id           NVARCHAR(32)  NOT NULL CONSTRAINT PK_EmailOtps PRIMARY KEY,   -- challenge id given to the browser
  Email        NVARCHAR(320) NOT NULL,                                        -- lower-case
  Purpose      NVARCHAR(20)  NOT NULL CONSTRAINT CK_EmailOtps_Purpose CHECK (Purpose IN (N'login', N'signup')),
  UserId       NVARCHAR(32)  NULL CONSTRAINT FK_EmailOtps_Users REFERENCES eSign.Users (Id) ON DELETE CASCADE,
  CodeHash     NVARCHAR(64)  NOT NULL,
  PayloadJson  NVARCHAR(MAX) NULL CONSTRAINT CK_EmailOtps_Payload CHECK (PayloadJson IS NULL OR ISJSON(PayloadJson) = 1),
  Attempts     INT           NOT NULL CONSTRAINT DF_EmailOtps_Attempts DEFAULT 0,
  ResendCount  INT           NOT NULL CONSTRAINT DF_EmailOtps_ResendCount DEFAULT 0,
  ExpiresAt    DATETIME2(0)  NOT NULL,
  LastSentAt   DATETIME2(0)  NOT NULL CONSTRAINT DF_EmailOtps_LastSentAt DEFAULT SYSUTCDATETIME(),
  ConsumedAt   DATETIME2(0)  NULL,
  IpAddress    NVARCHAR(64)  NULL,
  CreatedAt    DATETIME2(0)  NOT NULL CONSTRAINT DF_EmailOtps_CreatedAt DEFAULT SYSUTCDATETIME()
);
GO

/* Used to rate-limit how many codes one email can request */
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_EmailOtps_Email_Created' AND object_id = OBJECT_ID(N'eSign.EmailOtps'))
  CREATE INDEX IX_EmailOtps_Email_Created ON eSign.EmailOtps (Email, CreatedAt DESC);
GO

